const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const { performance } = require('node:perf_hooks');
const { _electron: electron } = require('playwright-core');
const { makeFixture } = require('./fixtures/contest-sessions.cjs');
const root = path.resolve(__dirname, '..');
const baseline = process.argv.includes('--baseline');
const output = path.join(root, 'output/playwright', `interaction-${baseline ? 'baseline' : 'candidate'}-${Date.now()}`);
const userData = path.join(output, 'profile'), templates = path.join(userData, 'templates');
fs.mkdirSync(templates, { recursive: true });
const fixture = makeFixture();
fixture.study.settings.reduceMotion = false;
fixture.cache.ratingHistory = Array.from({ length: 600 }, (_, i) => ({ contestId: i + 1, contestName: `Fixture ${i}`, handle: fixture.cache.handle, rank: 100 + i, oldRating: 1200 + i % 600, newRating: 1201 + i % 600, ratingUpdateTimeSeconds: 1700000000 + i * 86400 }));
for (let i = 0; i < 600; i++) fs.writeFileSync(path.join(templates, `template-${String(i).padStart(4, '0')}.cpp`), '// Performance fixture only\nint main() { return 0; }\n');
for (const [name, value] of [['cache', fixture.cache], ['study', fixture.study], ['template-library', { root: templates, overrides: {}, summaries: {} }]]) fs.writeFileSync(path.join(userData, `${name}.json`), JSON.stringify(value));
let app, page; const errors = [];
(async () => {
  const start = performance.now();
  const executablePath = process.env.CF_COMPASS_QA_EXECUTABLE || path.join(root, 'node_modules/electron/dist', process.platform === 'win32' ? 'electron.exe' : 'electron');
  app = await electron.launch({ executablePath, args: process.env.CF_COMPASS_QA_EXECUTABLE ? [] : [root], cwd: root, env: { ...process.env, CF_COMPASS_USER_DATA: userData } });
  page = await app.firstWindow(); page.on('pageerror', e => errors.push(e.message));
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.waitForSelector('.workbench-move');
  const startupMs = performance.now() - start;
  await page.getByRole('button', { name: '训练分析', exact: true }).click();
  await page.getByRole('tab', { name: '生涯', exact: true }).click();
  await page.waitForSelector('.rating-navigator__handle--start');
  const nav = page.locator('.rating-navigator');
  await nav.evaluate(el => { const get = el.getBoundingClientRect.bind(el); window.__layoutReads = 0; el.getBoundingClientRect = () => { window.__layoutReads++; return get(); }; });
  const box = await page.locator('.rating-navigator__handle--start').boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down();
  const dragMs = await page.locator('.rating-navigator__handle--start').evaluate(async (el) => {
    const start = performance.now(), box = el.getBoundingClientRect();
    for (let i = 0; i < 240; i++) el.dispatchEvent(new PointerEvent('pointermove', { bubbles: true, pointerId: 1, clientX: box.x + i / 2, clientY: box.y + 4 }));
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    return performance.now() - start;
  });
  await page.mouse.up();
  const layoutReads = await page.evaluate(() => window.__layoutReads);
  assert.ok(Number(await nav.getAttribute('data-visible-points')) < 600, 'drag changes visible window');
  await page.getByRole('button', { name: '模板库', exact: true }).click();
  await page.waitForSelector('[data-template-search]');
  const templateStart = performance.now();
  await page.locator('[data-template-search]').fill('template-');
  await page.waitForSelector('[data-template-card]');
  await page.waitForFunction(() => document.querySelector('.template-level-two__header')?.textContent.includes('600'));
  const templateMs = performance.now() - templateStart;
  const cards = await page.locator('[data-template-card]').count();
  if (!baseline) {
    assert.ok(layoutReads <= 3, `only initial layout reads, got ${layoutReads}`);
    assert.equal(cards, 60);
    await page.getByRole('button', { name: '加载更多模板', exact: true }).click();
    assert.equal(await page.locator('[data-template-card]').count(), 120);
    await page.locator('[data-template-search]').fill('template-0599');
    await page.waitForFunction(() => document.querySelectorAll('[data-template-card]').length === 1);
    assert.ok((await page.locator('[data-template-card]').textContent()).includes('0599'));
    await page.locator('[data-template-summary-open]').click();
    await page.waitForSelector('.template-summary-dialog');
  }
  assert.deepEqual(errors, []);
  const report = { baseline, fixture: { ratingHistory: 600, templates: 600, pointerEvents: 240 }, startupMs, dragMs, layoutReads, templateMs, cards, errors, note: 'Synthetic burst tests coalescing; wall-clock times are observations, not FPS or universal budgets.' };
  fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify({ ...report, output }));
})().catch(error => { fs.writeFileSync(path.join(output, 'failure.txt'), error.stack); console.error(error); process.exitCode = 1; }).finally(async () => { if (app) await app.close(); });
