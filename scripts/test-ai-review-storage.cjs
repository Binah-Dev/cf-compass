const assert = require('node:assert/strict');
const { sanitizeReviewEvidence } = require('../electron/services/ai-review-storage.cjs');
const source = { sourceTimeline: [{ submissionId: 1, relativeTimeSeconds: 0, sourceAvailable: true, apiKey: 'must-not-persist' }], sourceDiffs: [{ id: 'a', patch: '+hello\n world', fromSubmissionId: null }] };
const clean = sanitizeReviewEvidence(source);
assert.equal(clean.sourceTimeline[0].relativeTimeSeconds, 0);
assert.equal(clean.sourceTimeline[0].apiKey, undefined);
assert.equal(clean.sourceDiffs[0].patch, source.sourceDiffs[0].patch);
assert.deepEqual(sanitizeReviewEvidence(JSON.parse(JSON.stringify(clean))), clean);
assert.deepEqual(sanitizeReviewEvidence({}), { sourceTimeline: [], sourceDiffs: [], sourceTimelineCount: 0, sourceDiffCount: 0 });
const bounded = sanitizeReviewEvidence({ sourceDiffs: [{ patch: 'a'.repeat(80000) }, { patch: 'b'.repeat(80000) }], sourceTimeline: Array(500).fill({ submissionId: 1 }) });
assert.equal(bounded.sourceTimeline.length, 300);
assert.equal(bounded.sourceDiffs.reduce((n,x)=>n+x.patch.length,0), 60000);
assert.ok(bounded.sourceDiffs.every(x=>x.patchTruncated));
console.log('AI review evidence persistence and bounds passed');
const fs = require('node:fs'), path = require('node:path');
const frontend = fs.readFileSync(path.join(__dirname, '../src/lib/ai.js'), 'utf8');
const normalize = new Function(frontend.slice(frontend.indexOf('function safeText'), frontend.indexOf('function browserConfig')).replace('export function normalizeAiReview', 'function normalizeAiReview') + '; return normalizeAiReview;')();
const view = normalize({ sourceTimeline: [{ relativeTimeSeconds: null }], sourceDiffs: [{ fromSubmissionId: null, patch: ' context\n+new\n' }] });
assert.equal(view.sourceTimeline[0].relativeTimeSeconds, null);
assert.equal(view.sourceDiffs[0].fromSubmissionId, null);
assert.equal(view.sourceDiffs[0].patch, ' context\n+new\n');
assert.equal(normalize({sourceTimeline:[{relativeTimeSeconds:0}]}).sourceTimeline[0].relativeTimeSeconds,0);
console.log('Renderer preserves unknown times and Diff whitespace');
const component = fs.readFileSync(path.join(__dirname, '../src/components/ContestAiReview.jsx'), 'utf8');
const formatTime = new Function(component.slice(component.indexOf('function formatTimelineTime'), component.indexOf('function verdictLabel')) + ';return formatTimelineTime;')();
assert.equal(formatTime(null), '时间未知');
assert.equal(formatTime(0), '00:00:00');
const { waitUntil } = require('./qa-wait.cjs');
(async () => {
  let reads = 0;
  const value = await waitUntil(async () => ++reads, n => n === 3);
  assert.equal(value, 3);
  await assert.rejects(waitUntil(async () => false, Boolean, 1), /Timed out/);
  console.log('Async persistence poll waits for actual completion');
})().catch(error => { console.error(error); process.exitCode = 1; });
